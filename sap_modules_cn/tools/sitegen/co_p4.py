def _rot_label(opts, ans, k):
    keys = [a for a, _t in opts]
    texts = [t for _a, t in opts]
    i = keys.index(ans)
    texts = texts[k:] + texts[:k]
    return list(zip(keys, texts)), keys[(i - k) % len(keys)]


def _rot_expl(expl, old, new):
    if old != new:
        expl = expl.replace("答案 %s。" % old, "答案 %s。" % new, 1)
    return expl


