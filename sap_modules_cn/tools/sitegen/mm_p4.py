def page_glossary(ctx, stats):
    s = []
    s.append('<p class="lead">术语中英对照（教学用中文说法 + SAP 原生名称）、事务码速查、常用表 —— '
             '上课随时回来查。</p>')
    s.append(toc([("术语中英对照", "terms"), ("事务码速查", "tc"),
                  ("常用表", "tables"), ("教材任务总索引", "tasks")]))

    s.append('<h2 id="terms">术语中英对照（%d 条）</h2>' % len(GLOSSARY))
    s.append(tbl(["中文", "English / SAP 名称", "说明"],
                 [[esc(a), "<code>%s</code>" % esc(b), esc(c)] for a, b, c in GLOSSARY],
                 cls="tbl idx"))

    s.append('<h2 id="tc">事务码速查</h2>')
    rows = []
    for t in ctx.tasks:
        for c in (t.get("tcodes") or []):
            rows.append([c, t["title"], '<a href="config.html#t%02d">任务 %02d</a>' % (t["no"], t["no"])])
    s.append('<h3>教材出现的事务码（%d 个）</h3>' % len(set(r[0] for r in rows)))
    s.append(tbl(["T-code", "教材任务", "索引"],
                 sorted(rows, key=lambda r: r[0]) or [["—", "教材该模块未标注事务码", "—"]],
                 cls="tbl idx"))
    s.append('<h3>本模块常用事务码（含教材未演示的）</h3>')
    s.append(tbl(["T-code", "用途"], [[("<code>%s</code>" % a), esc(b)] for a, b in TCODES_EXTRA],
                 cls="tbl idx"))

    s.append('<h2 id="tables">常用表（查问题用）</h2>')
    s.append(tbl(["表", "内容"], [[("<code>%s</code>" % a), esc(b)] for a, b in TABLES], cls="tbl idx"))

    s.append('<h2 id="tasks">教材任务总索引（42 个）</h2>')
    s.append(tbl(["任务", "标题", "IMG 路径 / 前台路径", "截图"],
                 [['<a href="config.html#t%02d">%02d</a>' % (t["no"], t["no"]), esc(t["title"]),
                   esc((t.get("path") or "—")[:90]),
                   str(len(t["steps"]))] for t in ctx.tasks],
                 cls="tbl idx"))
    return s
