# パスではない行の個別修正（中国語 → 正規の日本語への置換）
PROSE_FIX = [('行項目を', '明細行を')]


def segs(text):
    parts = SEP.split(text)
    return parts[0::2], parts[1::2]


def fix_value(zh, ja):
    zs, _ = segs(zh)
    parts = SEP.split(ja)          # [seg, sep, seg, sep, …]
    jz = parts[0::2]
    if len(zs) >= 3 and len(zs) == len(jz):
        for i, z in enumerate(zs):
            key = z.strip()
            if key in CANON and parts[2 * i] != CANON[key]:
                parts[2 * i] = CANON[key]
        ja = ''.join(parts)
    for a, b in PROSE_FIX:
        ja = ja.replace(a, b)
    return ja


def main():
    dry = '--dry' in sys.argv
    for f in ('work/ja/model_map.json', 'work/ja/src_map.json'):
        zm = {'model': 'work/ja/model_atoms.json', 'src': 'work/ja/src_atoms.json'}[
            'model' if 'model' in f else 'src']
        z = json.load(open(zm, encoding='utf-8'))
        m = json.load(open(f, encoding='utf-8'))
        n, samples = 0, []
        for k, ja in list(m.items()):
            if k not in z:
                continue
            new = fix_value(z[k], ja)
            if new != ja:
                n += 1
                if len(samples) < 4:
                    samples.append((ja[:70], new[:70]))
                m[k] = new
        if not dry:
            json.dump(m, open(f, 'w', encoding='utf-8'), ensure_ascii=False, indent=0, sort_keys=True)
        print('%-28s fixed %d values%s' % (f, n, ' (dry)' if dry else ''))
        for a, b in samples:
            print('    - %s\n      + %s' % (a, b))


if __name__ == '__main__':
    main()
