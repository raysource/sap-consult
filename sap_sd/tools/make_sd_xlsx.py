def plain(t):
    t = re.sub(r"<br\s*/?>", "\n", str(t))
    t = re.sub(r"<[^>]+>", "", t)
    t = (t.replace("&nbsp;", " ").replace("&amp;", "&").replace("&lt;", "<")
          .replace("&gt;", ">").replace("&quot;", '"'))
    return re.sub(r"[ \t]+", " ", t).strip()


def table(ws, title, subtitle, headers, rows, widths):
    ncol = len(headers)
    last = get_column_letter(ncol)
    ws.merge_cells("A1:%s1" % last)
    c = ws.cell(1, 1, title); c.font = F_TITLE; c.fill = FILL_TITLE
    ws.row_dimensions[1].height = 26
    ws.merge_cells("A2:%s2" % last)
    ws.cell(2, 1, subtitle).font = F_SMALL
    ws.row_dimensions[2].height = 15
    for j, h in enumerate(headers, 1):
        c = ws.cell(3, j, h); c.font = F_HEAD; c.fill = FILL_HEAD
        c.alignment = CENTER; c.border = BORDER
    ws.row_dimensions[3].height = 22
    for i, row in enumerate(rows):
        r = 4 + i
        for j, v in enumerate(row, 1):
            c = ws.cell(r, j, v); c.font = F_BODY; c.alignment = WRAP; c.border = BORDER
            if i % 2 == 1:
                c.fill = FILL_ALT
        longest = max((len(str(x).split("\n")[0]) for x in row), default=0)
        lines = max((str(x).count("\n") + 1 for x in row), default=1)
        ws.row_dimensions[r].height = max(17, 13 * max(1, longest // 40) + 13 * (lines - 1))
    for j, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(j)].width = w
    ws.freeze_panes = ws.cell(4, 1)
    return 4 + len(rows)


def kv(ws, title, subtitle, rows, widths):
    return table(ws, title, subtitle, ["項目", "内容"], rows, widths)


