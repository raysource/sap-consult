def apply_fixups(pages):
    """pages: {page: {step_key: [screen, ...]}} を破壊的に補正する"""
    n = 0
    for (page, key, si, ci), (x, y) in FIXUPS.items():
        steps = pages.get(page) or {}
        screens = steps.get(key)
        if not screens or si > len(screens):
            raise SystemExit("fixup: 画面が見つかりません: %s / %s / %d" % (page, key, si))
        cos = screens[si - 1].get("callouts") or []
        if ci > len(cos):
            raise SystemExit("fixup: callout が見つかりません: %s / %s / %d / %d" % (page, key, si, ci))
        cos[ci - 1][1], cos[ci - 1][2] = x, y
        n += 1
    return n
