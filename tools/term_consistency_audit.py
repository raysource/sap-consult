def audit(sites):
    texts = {s: site_pages(s) for s in sites}
    blob = {s: ' '.join(p.values()) for s, p in texts.items()}

    def count(b, form):
        ex = EXCLUDES.get(form)
        pat = re.escape(form) + ('(?!' + '|'.join(map(re.escape, ex)) + ')' if ex else '')
        return len(re.findall(pat, b))

    print('=== A) 概念ごとの表記揺れ（2 表記以上＝要確認）===')
    rows = 0
    keep = []
    for label, forms in CONCEPTS:
        use = {f: {s: count(blob[s], f) for s in sites} for f in forms}
        use = {f: c for f, c in use.items() if sum(c.values())}
        if len(use) < 2:
            continue
        if label in KEEP_NOTES:
            keep.append(label)
            continue
        rows += 1
        print('  ● %s' % label)
        for f, c in sorted(use.items(), key=lambda kv: -sum(kv[1].values())):
            where = ', '.join('%s×%d' % (s.replace('sap_', ''), n) for s, n in c.items() if n)
            print('      %-16s %s' % (f, where))
    print('  （要確認 %d 概念 / 意図的な使い分け %d 概念）' % (rows, len(keep)))
    for lab in keep:
        print('  ○ %-14s … %s' % (lab, KEEP_NOTES[lab]))

    print('\n=== B) 長音符ゆれ（同一語の ー 有無）===')
    seen = 0
    for s in sites:
        for a, b in KANA_PAIRS:
            ca, cb = count(blob[s], a), count(blob[s], b)
            if ca and cb and a != b:
                print('  ● %-10s 「%s」×%d と 「%s」×%d' % (s, a, ca, b, cb))
                seen += 1
    print('  （%d 件）' % seen)

    print('\n=== C) 全角/半角・記号の併存 ===')
    for s in sites:
        b = blob[s]
        pairs = [('（ ）', '()'), ('／', '/'), ('，', ','), ('．', '.'), ('：', ':')]
        for full, half in [('（', '('), ('）', ')'), ('／', '/'), ('，', ','), ('：', ':')]:
            if full in b and half in b:
                print('  ● %-10s 「%s」 %d 回 と 「%s」 %d 回' % (s, full, b.count(full), half, b.count(half)))



    print('\n=== D) 簡体字（中国語）の残り ===')
    # 日本語の新字体では使わない簡体字だけを並べる（与・入・点・注・得 などは日本語なので除く）
    SIMP = ('们这为个说时页单对开过还进选击钮确认录销订购货库输图实题问师员练习线报织经历级训达备观标记价据执专导产类总览规额'
            '应该让请谢获务权责见电东军农兴举龙阳阴齿龟决况净减划则创计暂验结构术设备')
    found = 0
    for s in sites:
        hits = []
        for name, t in texts[s].items():
            for m in re.finditer('[' + SIMP + ']', t):
                hits.append((name, m.group(0), t[max(0, m.start() - 30):m.start() + 30].strip()))
        if hits:
            print('  ● %s: %d 文字' % (s, len(hits)))
            for name, ch, c in hits[:4]:
                print('      %-14s %s … %s' % (name, ch, c))
            found += len(hits)
    print('  （合計 %d 文字）' % found)


if __name__ == '__main__':
    audit(sys.argv[1:] or DEFAULT_SITES)
